def _draft_id(output: str) -> str:
    return re.search(r"--draft (ho-[0-9a-f]{8}) --yes", output).group(1)


# ---- reading sessions ----

def test_reads_the_codex_session_for_this_directory(project):
    path = write_codex_session(project)
    agent, found = sessions.find_session(project)
    assert (agent, found) == ("codex", path)
    turns = sessions.read_turns(agent, found)
    assert [t["role"] for t in turns] == ["user", "assistant", "user"]
    assert "AGENTS.md" not in json.dumps(turns)
    assert "Reject B" in turns[1]["text"]


def test_a_codex_session_in_another_directory_is_not_used(project, tmp_path):
    write_codex_session(tmp_path / "elsewhere")
    with pytest.raises(sessions.SessionNotFound):
        sessions.find_session(project)


def test_reads_the_claude_code_session_for_this_directory(project):
    path = write_claude_session(project)
    agent, found = sessions.find_session(project, "claude")
