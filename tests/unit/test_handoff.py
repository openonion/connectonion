def _row(kind, payload, when="2026-10-10T10:00:00Z"):
    return json.dumps({"timestamp": when, "type": kind, "payload": payload})


def _codex_message(role, text):
    kind = "input_text" if role == "user" else "output_text"
    return _row("response_item", {"type": "message", "role": role, "content": [{"type": kind, "text": text}]})


def write_codex_session(cwd: Path, extra: str = "") -> Path:
    folder = Path.home() / ".codex" / "sessions" / "2026" / "10" / "10"
    folder.mkdir(parents=True)
    path = folder / f"rollout-2026-10-10T10-00-00-{THREAD}.jsonl"
    rows = [
        _row("session_meta", {"id": THREAD, "cwd": str(cwd), "originator": "codex-tui", "source": "cli"}),
        _codex_message("user", "# AGENTS.md instructions\n\n<INSTRUCTIONS>house rules</INSTRUCTIONS>"),
        _codex_message("user", "Option A: httpOnly cookie. Option B: localStorage. Which for the login token?" + extra),
        _row("response_item", {"type": "function_call", "name": "shell", "arguments": "{}"}),
        _codex_message("assistant", "Reject B: any XSS can read localStorage. Go with A, the cookie."),
        _codex_message("user", "Agreed. Next is the middleware in auth/session.py."),
    ]
    path.write_text("\n".join(rows) + "\n")
    return path


