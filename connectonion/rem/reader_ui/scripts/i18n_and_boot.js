// What the language line says (the rc34 check: the top bar had grown to "369 页还没有中文版 · 翻译 · 遮住敏感 · EN"):
// the parts live in the language badge's menu and in the phone's 显示 menu; the bar itself shows only a count.
function langParts() {
  const job = translateAllJob || {}, busy = ["starting", "running", "stopping"].includes(job.state);
  // Before loadDetails() finishes, use snapshot's precomputed counts so the top bar never jumps between routes (#3364).
  const pre = !detailReady && Number.isFinite(REM.untranslated_count);
  const known = busy && job.total != null;
  const total = known ? job.total : pre && Number.isFinite(REM.written_count) ? REM.written_count : (REM.records || []).filter(r => r.written).length;
  const left = known ? Math.max(0, job.total - job.done) : pre ? REM.untranslated_count : untranslatedPages().length;
  const parts = [];
  if (uiLanguage === "zh" && busy) {
    parts.push(el("span", { text: job.total != null ? t("Chinese {n} / {m}", { n: job.done, m: job.total }) : t("Getting the pages ready…") }));
    const stop = el("button", { type: "button", class: "lang-act", text: t("Stop") });
    stop.disabled = job.state === "stopping";
    stop.onclick = () => translateAllSend("stop");
    parts.push(stop);
  } else if (uiLanguage === "zh" && left) {
    // The last night's translation failures, said here now that the body has no notice of its own (#3143).
    const run = (REM.logs || REM.brief_logs || []).find(run => /translat/.test(run.phase || ""));
    const failed = run?.translation_failures ?? (run?.pages || []).filter(page => page.outcome === "failed").length;
    if (failed) parts.push(el("span", { class: "lang-failed", text: t(failed === 1 ? "{n} page could not be translated." : "{n} pages could not be translated.", { n: failed }) }));
    parts.push(el("span", { text: t("{n} pages not in Chinese yet", { n: left }), title: t("Chinese {n} / {m}", { n: total - left, m: total }) }));
    if (liveHere()) {
      const go = el("button", { type: "button", class: "lang-act", text: t("Translate") });
      go.onclick = () => translateAllSend("start");
      parts.push(go);
    } else parts.push(el("span", { class: "lang-when", text: t("tonight") }));
  }
  return { parts, busy, left, job };
}
function renderLangProgress() {
  const box = document.getElementById("lang-progress");
  if (!box) return;
  const { parts, busy, left, job } = langParts();
  // An open menu stays open while the count moves (the Host polls during a translation); only its words change.
  const wasOpen = !!box.querySelector(".lang-menu");
  refreshDisplayLang(parts);
  if (!parts.length) { box.replaceChildren(); box.hidden = true; renderDisplayMenu(); return; }
  // A small count beside the toggle; while it translates, its progress.
  const badge = el("button", { type: "button", class: "lang-badge", "aria-haspopup": "menu", "aria-expanded": "false",
    title: parts.map(part => part.textContent).join(" · ") }, langBadgeWords(busy && job.total != null ? job : null, left));
  badge.onclick = event => { event.stopPropagation(); toggleLangMenu(); };
  box.replaceChildren(badge);
  box.hidden = false;
  if (wasOpen) toggleLangMenu(true);
  renderDisplayMenu();
}
