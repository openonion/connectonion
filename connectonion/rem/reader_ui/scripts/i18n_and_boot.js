function refreshDisplayLang(parts) {
  const pop = document.querySelector(".display-pop");
  if (!pop) return;
  const shown = pop.querySelector(".dp-lang");
  if (!parts.length) { shown?.remove(); return; }
  const fresh = el("div", { class: "dp-lang" }, parts);
  if (shown) shown.replaceWith(fresh); else pop.querySelector(".dp-row").after(fresh);
}
